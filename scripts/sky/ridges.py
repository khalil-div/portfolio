"""Generates the Hajar-mountain ridgelines in src/lib/hajar.ts.

Midpoint displacement with a fixed seed, so the mountains are identical on
every build. Three ridges: far (soft, high), mid, near (jagged, low).
Run: python3 scripts/sky/ridges.py
"""
import random

W, H = 1600, 200

def ridge(seed, base, rough, amp, peaks):
    rnd = random.Random(seed)
    pts = {0: base + rnd.uniform(-amp, amp) * 0.3, W: base + rnd.uniform(-amp, amp) * 0.3}
    # a few deliberate summits give the skyline its Hajar character
    for x, h in peaks:
        pts[x] = base - h
    def split(a, b, spread):
        if b - a < 22:
            return
        m = (a + b) // 2
        if m not in pts:
            pts[m] = (pts[a] + pts[b]) / 2 + rnd.uniform(-spread, spread)
        split(a, m, spread * rough)
        split(m, b, spread * rough)
    keys = sorted(pts)
    for a, b in zip(keys, keys[1:]):
        split(a, b, amp)
    return [(x, max(40.0, min(H - 4.0, y))) for x, y in sorted(pts.items())]

# Crests stay below y≈40 so the top is never cropped (see .sky-ridges).
RIDGES = {
    "far": ridge(11, 100, 0.5, 26, [(260, 34), (620, 52), (1080, 42), (1430, 30)]),
    "mid": ridge(23, 132, 0.5, 19, [(140, 17), (470, 37), (900, 26), (1290, 44)]),
    "near": ridge(37, 166, 0.48, 13, [(330, 22), (760, 14), (1180, 29), (1520, 12)]),
}

def crest_at(pts, x):
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        if x0 <= x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return pts[-1][1]

def city(seed):
    """Muscat at night, seen over the foothills: lights on the slopes below
    the middle ridge, clustered in the valleys. The near ridge is drawn in
    front, so some are hidden behind it. (x, y, r, group) in viewBox units;
    `group` staggers the twinkle."""
    rnd = random.Random(seed)
    mid, near = RIDGES["mid"], RIDGES["near"]
    lights = []
    for cx, spread, count in [(120, 110, 30), (430, 150, 52), (820, 120, 36), (1180, 160, 56), (1500, 90, 26)]:
        for _ in range(count):
            x = rnd.gauss(cx, spread / 2)
            if not 4 < x < W - 4:
                continue
            top = crest_at(mid, x) + 5
            y = top + abs(rnd.gauss(0, 14))
            if y > crest_at(near, x) + 2:  # fully behind the foothills
                continue
            lights.append((x, y, rnd.uniform(1.2, 2.2), rnd.randrange(3)))
    return sorted(lights)

CITY = city(53)

def fmt(pts):
    return " ".join(f"{x:.0f} {y:.1f}" for x, y in pts)

out = [
    "// Generated by scripts/sky/ridges.py — do not edit by hand.",
    f"export const HAJAR_VIEWBOX = \"0 0 {W} {H}\";",
    "",
    "/** Crest lines (open) and filled silhouettes for each ridge, far → near. */",
    "export const HAJAR = {",
]
for name, pts in RIDGES.items():
    crest = "M" + fmt(pts[:1]) + " L" + fmt(pts[1:])
    out.append(f"  {name}: {{")
    out.append(f"    crest: \"{crest}\",")
    out.append(f"    fill: \"{crest} L{W} {H} L0 {H} Z\",")
    out.append("  },")
out.append("} as const;")
out.append("")
out.append("/** City lights: [x, y, radius, twinkle group]. */")
out.append("export const CITY: [number, number, number, number][] = [")
for x, y, r, g in CITY:
    out.append(f"  [{x:.0f}, {y:.1f}, {r:.1f}, {g}],")
out.append("];")
open("src/lib/hajar.ts", "w").write("\n".join(out) + "\n")
print({k: len(v) for k, v in RIDGES.items()}, "city", len(CITY))
