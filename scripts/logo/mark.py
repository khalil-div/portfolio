"""Generates the logo, "k.": a lowercase k in Readex Pro (600) and an orange
full stop, the sun. Fitted to a 100×100 tile.

Writes src/lib/logo.ts (paths for the Logo component), src/app/icon.svg
(browser tab) and scripts/og/apple-icon.html (iPhone icon, rendered by
scripts/og/render.mjs).

  python3 -m venv .venv && .venv/bin/pip install fonttools
  curl -L -o ReadexPro.ttf "https://github.com/google/fonts/raw/main/ofl/readexpro/ReadexPro%5BHEXP%2Cwght%5D.ttf"
  .venv/bin/python scripts/logo/mark.py ReadexPro.ttf
"""
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

INK, PAPER, SUN = "#0f0f10", "#f5f4f0", "#ff4f17"
TOP, LEFT, HEIGHT = 22, 24, 56  # the k's ink box in the tile
GAP, RADIUS = 3, 6.6  # full stop: gap after the k, and its size

font = instantiateVariableFont(TTFont(sys.argv[1]), {"wght": 600, "HEXP": 0})
glyphs = font.getGlyphSet()
num = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")

k = glyphs[font.getBestCmap()[ord("k")]]
bounds = BoundsPen(glyphs)
k.draw(bounds)
x0, y0, x1, y1 = bounds.bounds  # font units, y up
s = HEIGHT / (y1 - y0)
pen = SVGPathPen(glyphs, ntos=num)
k.draw(TransformPen(pen, (s, 0, 0, -s, LEFT - x0 * s, TOP + y1 * s)))
letter = pen.getCommands()

cx, cy, r = LEFT + (x1 - x0) * s + GAP + RADIUS, TOP + HEIGHT - RADIUS, RADIUS
sun = f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0Z"

open("src/lib/logo.ts", "w").write(
    "// Generated by scripts/logo/mark.py — do not edit by hand.\n"
    '/** "k.": the letter and its full stop (the sun), fitted to a 100×100 tile. */\n'
    f'export const LOGO = {{ letter: "{letter}", sun: "{sun}" }} as const;\n'
)

def svg(tile):
    rect = f'<rect width="100" height="100" rx="28" fill="{INK}"/>' if tile else ""
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">{rect}<path d="{letter}" fill="{PAPER}"/><path d="{sun}" fill="{SUN}"/></svg>'

open("src/app/icon.svg", "w").write(svg(True) + "\n")
open("scripts/og/apple-icon.html", "w").write(
    "<!doctype html>\n<!-- iPhone home-screen icon: the logo, full-bleed (iOS rounds the corners itself).\n"
    "     Generated by scripts/logo/mark.py. -->\n"
    f'<html><head><meta charset="utf-8" /><style>*{{margin:0}}body{{width:180px;height:180px;background:{INK}}}'
    "svg{display:block;width:180px;height:180px}</style></head><body>\n" + svg(False) + "\n</body></html>\n"
)
print("letter", len(letter), "sun at", num(cx), num(cy))
