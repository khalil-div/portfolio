"""Generates src/lib/logos.ts: the four English logo candidates, every shape
already fitted to a 100×100 tile, from Readex Pro (600).

  e1  k.                  lowercase k + an orange full stop (the sun)
  e2  K holding the sun   the sun nested in the open V of the K
  e3  KA                  K + an A drawn as a mountain, the sun rising inside
  e4  Khalil.             the name is the logo; this is its "K." icon

  python3 -m venv .venv && .venv/bin/pip install fonttools
  curl -L -o ReadexPro.ttf "https://github.com/google/fonts/raw/main/ofl/readexpro/ReadexPro%5BHEXP%2Cwght%5D.ttf"
  .venv/bin/python scripts/logo/marks.py ReadexPro.ttf
"""
import json
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

font = instantiateVariableFont(TTFont(sys.argv[1]), {"wght": 600, "HEXP": 0})
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
num = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")


def letter(char, x, y, height):
    """The glyph's ink, `height` tall, top-left at (x, y) in tile units."""
    g = glyphs[cmap[ord(char)]]
    b = BoundsPen(glyphs)
    g.draw(b)
    x0, y0, x1, y1 = b.bounds  # font units, y up
    s = height / (y1 - y0)
    pen = SVGPathPen(glyphs, ntos=num)
    g.draw(TransformPen(pen, (s, 0, 0, -s, x - x0 * s, y + y1 * s)))
    return pen.getCommands(), (x1 - x0) * s


def disc(cx, cy, r):
    return f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0Z"


k, kw = letter("k", 24, 22, 56)
K2, _ = letter("K", 24, 22, 56)
K3, _ = letter("K", 15, 28, 44)
K4, k4w = letter("K", 22, 24, 52)

LOGOS = {
    "e1": {"letters": [k], "strokes": [], "sun": disc(24 + kw + 3 + 6.6, 22 + 56 - 6.6, 6.6)},
    "e2": {"letters": [K2], "strokes": [], "sun": disc(69, 50, 7.5)},
    "e3": {"letters": [K3], "strokes": ["M55 72 70 30 85 72"], "sun": "M62 72a8 8 0 0 1 16 0Z"},
    "e4": {"letters": [K4], "strokes": [], "sun": disc(22 + k4w + 9, 70, 6)},
}

open("src/lib/logos.ts", "w").write(
    "// Generated by scripts/logo/marks.py — do not edit by hand.\n"
    "/** Logo candidates, every shape fitted to a 100×100 tile. */\n"
    f"export const LOGOS = {json.dumps(LOGOS)} as const;\n\n"
    "export type LogoId = keyof typeof LOGOS;\n"
)
print({key: sum(len(p) for p in v["letters"]) for key, v in LOGOS.items()})
