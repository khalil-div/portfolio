"""Generates the logo: خ in Readex Pro (bold), fitted to a 100×100 tile.

Writes src/lib/logo.ts (paths for the Logo component), src/app/icon.svg
(browser tab) and scripts/og/apple-icon.html (iPhone icon, rendered by
scripts/og/render.mjs). خ is the body ح plus a dot; the dot is drawn
separately so it can be the orange sun.

  python3 -m venv .venv && .venv/bin/pip install fonttools
  curl -L -o ReadexPro.ttf "https://github.com/google/fonts/raw/main/ofl/readexpro/ReadexPro%5BHEXP%2Cwght%5D.ttf"
  .venv/bin/python scripts/logo/khah.py ReadexPro.ttf
"""
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

INK, PAPER, SUN = "#0f0f10", "#f5f4f0", "#ff4f17"
HEIGHT = 66  # letter height, in % of the tile
SUN_SCALE = 1.4  # the dot, enlarged so it reads as a sun even at 16 px

font = instantiateVariableFont(TTFont(sys.argv[1]), {"wght": 700, "HEXP": 0})
glyphs = font.getGlyphSet()
composite = font["glyf"]["uni062E"]  # خ = ح + dot
(body_name, *_), (dot_name, dot_x, dot_y) = [(c.glyphName, c.x, c.y) for c in composite.components]

def bounds(name, dx=0, dy=0):
    pen = BoundsPen(glyphs)
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, 1, dx, dy)))
    return pen.bounds

bx0, by0, bx1, by1 = bounds(body_name)
dx0, dy0, dx1, dy1 = bounds(dot_name, dot_x, dot_y)
x0, y0, x1, y1 = min(bx0, dx0), min(by0, dy0), max(bx1, dx1), max(by1, dy1)
scale = HEIGHT / (y1 - y0)

def path(name, dx=0, dy=0, grow=1.0):
    # font units (y up) → tile units (y down), letter centred in the tile
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    t = (scale, 0, 0, -scale, 50 - (cx - dx) * scale, 50 + (cy - dy) * scale)
    if grow != 1.0:  # scale about the shape's own centre
        b = BoundsPen(glyphs)
        glyphs[name].draw(TransformPen(b, t))
        mx, my = (b.bounds[0] + b.bounds[2]) / 2, (b.bounds[1] + b.bounds[3]) / 2
        t = (t[0] * grow, 0, 0, t[3] * grow, mx + (t[4] - mx) * grow, my + (t[5] - my) * grow)
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    glyphs[name].draw(TransformPen(pen, t))
    return pen.getCommands()

body = path(body_name)
dot = path(dot_name, dot_x, dot_y, SUN_SCALE)

open("src/lib/logo.ts", "w").write(
    "// Generated by scripts/logo/khah.py — do not edit by hand.\n"
    "/** خ in Readex Pro, fitted to a 100×100 tile: the letter, and its dot (the sun). */\n"
    f'export const LOGO = {{ letter: "{body}", sun: "{dot}" }} as const;\n'
)

def svg(tile_rx, letter_fill):
    tile = f'<rect width="100" height="100" rx="{tile_rx}" fill="{INK}"/>' if tile_rx is not None else ""
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">{tile}<path d="{body}" fill="{letter_fill}"/><path d="{dot}" fill="{SUN}"/></svg>'

open("src/app/icon.svg", "w").write(svg(28, PAPER) + "\n")
open("scripts/og/apple-icon.html", "w").write(
    "<!doctype html>\n<!-- iPhone home-screen icon: the logo, full-bleed (iOS rounds the corners itself).\n"
    "     Generated by scripts/logo/khah.py. -->\n"
    f'<html><head><meta charset="utf-8" /><style>*{{margin:0}}body{{width:180px;height:180px;background:{INK}}}'
    "svg{display:block;width:180px;height:180px}</style></head><body>\n"
    + svg(None, PAPER) + "\n</body></html>\n"
)
print("letter", len(body), "sun", len(dot), "scale", round(scale, 4))
