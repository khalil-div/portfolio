"""Generates src/lib/signature.ts: Khalil's name as SVG glyph outlines, in
Readex Pro, one path per glyph in writing order (right-to-left for Arabic).

Shaping uses HarfBuzz, so Arabic letters take their correct joined forms.

  python3 -m venv .venv && .venv/bin/pip install uharfbuzz fonttools
  curl -L -o ReadexPro.ttf "https://github.com/google/fonts/raw/main/ofl/readexpro/ReadexPro%5BHEXP%2Cwght%5D.ttf"
  .venv/bin/python scripts/signature/name.py ReadexPro.ttf
"""
import json
import sys

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

NAMES = {
    "ar": ("خليل البلوشي", "rtl", "arab", "ar", 600),
    "en": ("Khalil Alblushi", "ltr", "latn", "en", 500),
}


def outline(path, text, direction, script, language, weight):
    font = instantiateVariableFont(TTFont(path), {"wght": weight, "HEXP": 0})
    font.save("/tmp/readex-instance.ttf")
    blob = hb.Blob.from_file_path("/tmp/readex-instance.ttf")
    hbfont = hb.Font(hb.Face(blob))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.direction, buf.script, buf.language = direction, script, language
    hb.shape(hbfont, buf, {"kern": True, "liga": True})

    glyphs = font.getGlyphSet()
    order = font.getGlyphOrder()
    ascender = font["hhea"].ascent
    x = 0
    paths = []
    bounds = BoundsPen(glyphs)
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.0f}")
        dx, dy = x + pos.x_offset, pos.y_offset
        # Font units are y-up; SVG is y-down.
        flip = (1, 0, 0, -1, dx, ascender - dy)
        glyph = glyphs[order[info.codepoint]]
        glyph.draw(TransformPen(pen, flip))
        glyph.draw(TransformPen(bounds, flip))
        d = pen.getCommands()
        if d:
            paths.append((dx, d))
        x += pos.x_advance
    if direction == "rtl":
        paths.reverse()  # HarfBuzz returns visual order; Arabic is written right to left
    # Frame the real ink, not the font's nominal descent: Arabic dots can
    # sit well below it (the final ي's dots do).
    x0, y0, x1, y1 = bounds.bounds
    pad = 40
    box = [round(x0 - pad), round(y0 - pad), round(x1 - x0 + 2 * pad), round(y1 - y0 + 2 * pad)]
    return {"viewBox": " ".join(map(str, box)), "glyphs": [d for _, d in paths]}


def main():
    out = {lang: outline(sys.argv[1], *spec) for lang, spec in NAMES.items()}
    ts = [
        "// Generated by scripts/signature/name.py — do not edit by hand.",
        "/** The name as Readex Pro outlines, one path per glyph in writing order. */",
        f"export const SIGNATURE = {json.dumps(out, ensure_ascii=False)} as const;",
        "",
    ]
    open("src/lib/signature.ts", "w").write("\n".join(ts))
    for lang, data in out.items():
        print(lang, len(data["glyphs"]), "glyphs, viewBox", data["viewBox"])


main()
